/* ==========================================================================
   온라인 수업(영상) 설정 — 이 파일 하나만 고치면 됩니다.

   - 비어 있는(null) 항목이 하나라도 있으면 기능 전체가 꺼지고,
     교수자 화면(/lesson, 교수자 로그인 시)에 빠진 항목이 표시됩니다.
   - 시각은 반드시 한국 시간(+09:00)을 붙여 적습니다. 예: "2026-10-20T19:00:00+09:00"
     → 학생 기기의 시간대 설정과 상관없이 같은 순간으로 해석됩니다.
   - videoUrl 은 공개 MP4 주소(R2 사용자 지정 도메인)만 넣습니다. R2 API 키는 절대 넣지 않습니다.
   ========================================================================== */

export interface OnlineLessonConfig {
  /** 수업 구분용 ID(팝업 재표시 방지 키에 쓰임). 수업이 바뀌면 함께 바꾸세요. */
  id: string | null;
  /** 수업 제목 */
  title: string | null;
  /** 공개 MP4 주소. 예: "https://video.내도메인/lesson-01.mp4" */
  videoUrl: string | null;
  /** 수업 안내·입장 시작(한국 시간). 예: "2026-10-20T19:00:00+09:00" */
  startAt: string | null;
  /** 수업 안내·신규 입장 종료(한국 시간). 이미 시청 중인 사람은 끝까지 볼 수 있습니다. */
  endAt: string | null;
  /** 수업 페이지에 표시할 안내문(줄바꿈 가능) */
  notice: string | null;
  /**
   * 교수자 미리보기(선택). 이 시간 동안에는 교수자 계정에만 팝업·수업 시작이 열립니다.
   * 학생에게는 아무 영향이 없습니다. 쓰지 않을 때는 null.
   */
  instructorPreview: { startAt: string; endAt: string } | null;
}

